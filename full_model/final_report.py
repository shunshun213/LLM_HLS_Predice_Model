"""Final validation of the closed model (Target_refined section 7, stage2_impl Step 5).

Prediction path = the deliverable: HLS source (inline pragmas; Tcl directives when the source has
none) + clock -> stage1_parse -> stage1 -> stage2. Ground truth = csynth reports (dataset targets).

Writes reports/FINAL_VALIDATION.md:
  1. headline end-to-end on train (216): pass rate (Judgement A), MAPE, median / p90 APE,
     Spearman / Kendall (Judgement B), fits accuracy + not-fit precision / recall;
     targets of the session: MAPE latency < 10 %, LUT / FF / DSP / BRAM < 20 %
  2. the same on the true HS (Stage 2 alone) and on extra (development set)
  3. per-group breakdown on train
  4. LOGO of the Stage 2 constants (Stage 1 rules are in-sample for every group)
  5. stage-wise HS exact match (from stage1_report.sections)
  6. robustness over the design space (fuzz_design_space)
"""
import os, sys, json, statistics, collections
_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
from scipy.stats import spearmanr, kendalltau
import stage1, stage2, sanitize, evaluate, fit, fuzz_design_space
from stage1_report import cfg_of, sections, rows

M = ['latency_cycles', 'LUT', 'FF', 'DSP', 'BRAM_18K']
TARGET_MAPE = {'latency_cycles': 0.10, 'LUT': 0.20, 'FF': 0.20, 'DSP': 0.20, 'BRAM_18K': 0.20}
TOL = evaluate.TOL


def ape(p, t):
    return evaluate.ape(p, t)


def stats(P, T, m):
    e = [ape(p, t) for p, t in zip(P, T)]
    fin = [x for x in e if x != float('inf')]
    return dict(n=len(e), pass_=sum(x <= TOL[m] + 1e-12 for x in e) / len(e),
                mape=statistics.mean(fin), med=statistics.median(fin),
                p90=sorted(fin)[int(0.9 * len(fin)) - 1] if fin else 0,
                rho=spearmanr(P, T).correlation, tau=kendalltau(P, T).correlation, inf=len(e) - len(fin))


def fits_stats(Pf, Tf):
    acc = sum(a == b for a, b in zip(Pf, Tf)) / len(Pf)
    nf_t = [i for i, t in enumerate(Tf) if not t]
    nf_p = [i for i, p in enumerate(Pf) if not p]
    rec = sum(1 for i in nf_t if not Pf[i]) / len(nf_t) if nf_t else float('nan')
    prec = sum(1 for i in nf_p if not Tf[i]) / len(nf_p) if nf_p else float('nan')
    return acc, prec, rec, len(nf_t)


def confidence_flags(x):
    import predict
    cfg = cfg_of(x['r'])
    return [c for c in predict.confidence(cfg, stage1.predict_hs(cfg)) if not c.startswith('note')]


def main():
    S2 = {r['sample']: r for r in evaluate.load()}
    recs = []
    for r in rows:
        cfg = cfg_of(r)
        hs = stage1.predict_hs(cfg)
        sh = sanitize.sanitize(hs)
        th = sanitize.sanitize(S2[r['sample']]['input_hs'])
        recs.append(dict(r=r, hs=sh, sec=sections(sh, th), p=stage2.predict(hs), q=stage2.predict(th),
                         t=S2[r['sample']]['targets']))
    L = []
    w = L.append
    w('# Final validation: GEMM HLS model (HLS code + clock -> latency, LUT, FF, DSP, BRAM_18K, fits)\n')
    w('Generated by `final_report.py`. Prediction path: source pragmas (Tcl if the source has none) + '
      'clock -> `stage1_parse` -> `stage1` -> `stage2` (the same path as `predict.py`). '
      'No tool output is read on the prediction path.\n')
    w('**Scope.** Rules (Stage 1) and per-unit constants (Stage 2) were derived from all 510 designs; '
      'all numbers here are in-sample. LOGO (section 4) holds out a group from the Stage-2 constant fit '
      'only. The final test set is hidden.\n')

    def table(sel, key, title):
        w(f'### {title}\n')
        w('| metric | MAPE | session target | median APE | p90 APE | pass A | Spearman | Kendall |')
        w('|---|---|---|---|---|---|---|---|')
        for m in M:
            s = stats([x[key][m] for x in sel], [x['t'][m] for x in sel], m)
            ok = 'met' if s['mape'] < TARGET_MAPE[m] else 'NOT met'
            w(f"| {m} | **{100 * s['mape']:.1f} %** | < {100 * TARGET_MAPE[m]:.0f} % ({ok}) | {100 * s['med']:.1f} % | "
              f"{100 * s['p90']:.1f} % | {100 * s['pass_']:.1f} % | {s['rho']:.4f} | {s['tau']:.4f} |"
              + (f" ({s['inf']} with target 0 excluded from APE)" if s['inf'] else ''))
        acc, prec, rec, nnf = fits_stats([x[key]['fits'] for x in sel], [x['t']['fits'] for x in sel])
        w(f'\nfits flag: accuracy {100 * acc:.1f} %, not-fit class ({nnf} designs): precision '
          f'{100 * prec:.1f} %, recall {100 * rec:.1f} %\n')

    train = [x for x in recs if x['r']['source'] == 'train']
    extra = [x for x in recs if x['r']['source'] == 'extra']
    w('## 1. Headline: end to end on train (n = 216)\n')
    table(train, 'p', 'Stage 1 -> Stage 2 (the model)')
    w('## 2. Reference points\n')
    table(train, 'q', 'Stage 2 on the tool HS (train): cost-model error alone')
    table(extra, 'p', 'End to end on extra (development set, n = 294)')

    w('## 3. Per group, train, end to end (MAPE % / pass A %)\n')
    groups = sorted({x['r']['suite'] for x in train})
    w('| group | n | ' + ' | '.join(M) + ' |'); w('|---|---|' + '---|' * len(M))
    for g in groups:
        S = [x for x in train if x['r']['suite'] == g]
        cells = []
        for m in M:
            s = stats([x['p'][m] for x in S], [x['t'][m] for x in S], m)
            cells.append(f"{100 * s['mape']:.1f} / {100 * s['pass_']:.0f}")
        w(f'| {g} | {len(S)} | ' + ' | '.join(cells) + ' |')

    w('\n## 4. Generalization of the Stage 2 constants (Stage-1 HS as input, train)\n')
    w('The Stage 1 rules are in-sample in every row below; only the Stage 2 per-unit constants are '
      'held out.\n')
    data = fit.collect(evaluate.load())
    lp = {}
    for g in groups:
        C = fit.fit(data, holdout=g)
        for x in train:
            if x['r']['suite'] == g:
                lp[x['r']['sample']] = stage2.predict(x['hs'], C)
    # constants fitted on the extra sweeps only (train never seen by the fit)
    data_x = {k: [p for p in v if p[3] in {x['r']['sample'] for x in extra}] for k, v in data.items()}
    Cx = fit.fit(data_x)
    xp = {x['r']['sample']: stage2.predict(x['hs'], Cx) for x in train}
    w('| metric | in-sample MAPE | LOGO MAPE | LOGO pass A | extra-only fit MAPE |'); w('|---|---|---|---|---|')
    for m in M:
        T_ = [x['t'][m] for x in train]
        s0 = stats([x['p'][m] for x in train], T_, m)
        s1 = stats([lp[x['r']['sample']][m] for x in train], T_, m)
        s2 = stats([xp[x['r']['sample']][m] for x in train], T_, m)
        w(f"| {m} | {100 * s0['mape']:.1f} % | {100 * s1['mape']:.1f} % | {100 * s1['pass_']:.1f} % | {100 * s2['mape']:.1f} % |")
    w('\nPer group, LUT / FF MAPE (in-sample, LOGO, extra-only fit):\n')
    w('| group | n | LUT | FF |'); w('|---|---|---|---|')
    for g in groups:
        S = [x for x in train if x['r']['suite'] == g]
        cells = []
        for m in ('LUT', 'FF'):
            T_ = [x['t'][m] for x in S]
            a = stats([x['p'][m] for x in S], T_, m)['mape']
            b = stats([lp[x['r']['sample']][m] for x in S], T_, m)['mape']
            c = stats([xp[x['r']['sample']][m] for x in S], T_, m)['mape']
            cells.append(f'{100 * a:.1f} / {100 * b:.1f} / {100 * c:.1f}')
        w(f'| {g} | {len(S)} | ' + ' | '.join(cells) + ' |')
    w('\nMean signed error (bias, prediction - true, relative) per group, end to end:\n')
    w('| group | LUT bias | FF bias |'); w('|---|---|---|')
    for g in groups + ['ALL']:
        S = [x for x in train if g == 'ALL' or x['r']['suite'] == g]
        b = [statistics.mean((x['p'][m] - x['t'][m]) / x['t'][m] for x in S if x['t'][m]) for m in ('LUT', 'FF')]
        w(f'| {g} | {100 * b[0]:+.1f} % | {100 * b[1]:+.1f} % |')
    w('\n**Risk for the hidden test set.** The `mixed` group (99 of 216 train designs, random '
      'combinations of every pragma) is the most test-like. Its LUT/FF error is the largest and grows '
      'when its own designs are held out of the Stage 2 fit (see the table). Designs that combine '
      'several reshape / partition / storage pragmas, or that trigger a low-confidence rule (reported '
      'by `predict.py` under `confidence`), should be expected to carry LUT / FF errors above 20 %, '
      'with a tendency to under-predict (negative bias on `mixed`, table above); '
      'latency, DSP and BRAM are structural counts and generalize much better.\n')
    fl = [x for x in train if confidence_flags(x)]
    nf = [x for x in train if not confidence_flags(x)]
    for name, S in (('designs with a confidence flag', fl), ('designs without', nf)):
        if S:
            w(f"- {name} ({len(S)}): LUT MAPE {100 * stats([x['p']['LUT'] for x in S], [x['t']['LUT'] for x in S], 'LUT')['mape']:.1f} %, "
              f"FF MAPE {100 * stats([x['p']['FF'] for x in S], [x['t']['FF'] for x in S], 'FF')['mape']:.1f} %")

    w('\n## 5. Stage-wise exact match of the predicted HS (train / extra)\n')
    names = sorted({k for x in recs for k in x['sec']})
    w('| section | train | extra |'); w('|---|---|---|')
    for k in names:
        cells = []
        for S in (train, extra):
            a = sum(x['sec'].get(k, (0, 0))[0] for x in S); b = sum(x['sec'].get(k, (0, 0))[1] for x in S)
            cells.append(f'{100 * a / b:.1f} % ({a}/{b})' if b else '-')
        w(f'| {k} | {cells[0]} | {cells[1]} |')

    w('\n## 6. Robustness over the design space\n')
    import io, contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        bad, _ = fuzz_design_space.main(5000, seed=7)
    w(f"5000 random pragma sets over the whole Target design space (pipeline on none / k / j / i, "
      f"unroll factors incl. non-divisors of 64, every partition / reshape / storage / bind_op option, "
      f"4 clocks), each rendered as a Tcl script and as a C++ source with inline pragmas and parsed "
      f"back through `stage1_parse`: {bad['ok']} identical round trips with finite predictions, "
      f"{5000 - bad['ok']} failures. `test_parser.py` covers non-canonical syntax and out-of-space "
      f"input (clean `UnsupportedDesign` errors).\n")

    txt = '\n'.join(L) + '\n'
    open(os.path.join(_HERE, 'reports', 'FINAL_VALIDATION.md'), 'w').write(txt)
    print(txt)


if __name__ == '__main__':
    main()
