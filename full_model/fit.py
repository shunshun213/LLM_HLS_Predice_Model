"""Derive per-unit cost constants (non-negative) for the Expression / Multiplexer / Register
categories from the reports, one small set of physical quantities per (module class,
category, resource). Writes constants.json. Usage: python3 fit.py [holdout_group]"""
import json, sys, collections, os
import numpy as np
from scipy.optimize import nnls
import evaluate, sanitize, features, resources

# Coefficients fixed by physics (not fitted): one FF per one-hot FSM state, per loop-counter
# bit and per hoisted data bit held in a register.
FIXED = {
    ('top', 'Register', 'FF'): {'states': 1.0, 'cnt_bits': 1.0, 'hoist_reg_bits': 1.0, 'shl_reg_bits': 1.0},
    ('copy_in', 'Register', 'FF'): {'shl_reg_bits': 1.0},
    ('compute', 'Register', 'FF'): {'shl_reg_bits': 1.0, 'stages': 1.0},
}
# basis per (class, category, resource): only quantities with a hardware meaning
BASIS = {
    ('copy_in', 'Expression', 'LUT'): ['one', 'wide_inner', 'wide_outer', 'banks', 'shl_merge_bits'],
    ('copy_in', 'Expression', 'FF'): [],
    ('copy_in', 'Multiplexer', 'LUT'): ['one'],
    ('copy_in', 'Register', 'FF'): ['one', 'depth_x_32', 'wide_inner', 'wide_bits_x_depth', 'banks'],
    ('copy_in', 'Register', 'LUT'): [],
    ('copy_out', 'Expression', 'LUT'): ['one', 'wide_inner', 'wide_outer', 'banks'],
    ('copy_out', 'Multiplexer', 'LUT'): ['one'],
    ('copy_out', 'Register', 'FF'): ['one', 'depth_x_32', 'wide_bits_x_depth', 'banks'],
    ('copy_out', 'Register', 'LUT'): [],
    ('compute', 'Expression', 'LUT'): ['one', 'cnt_bits', 'addr_ops', 'addr_partial', 'dyn_read_pc', 'dyn_read_wide', 'dyn_write_bits', 'dyn_hoist_bits', 'shl_merge_bits'],
    ('compute', 'Expression', 'FF'): [],
    ('compute', 'Multiplexer', 'LUT'): ['one', 'mux_ii', 'banks_sel', 'II_states'],
    ('compute', 'Register', 'FF'): ['cnt_bits', 'depth_ov', 'depth_ov_ext', 'chain_wait', 'early_ops', 'core_regs_shared', 'P32_partial'],
    ('compute', 'Register', 'LUT'): ['sum_live'],
    ('top', 'Expression', 'LUT'): ['n_loops', 'body_P', 'hoist_seq', 'body_wide_sel', 'body_wide_sel_wide', 'body_dyn_write', 'top_wide_bits', 'top_c_lane', 'shl_merge_bits'],
    ('top', 'Expression', 'FF'): [],
    ('top', 'Multiplexer', 'LUT'): ['n_loops', 'hoist_seq', 'states', 'mem_arrays_banks', 'shared_call_mux', 'mux_body', 'hoist_reg_bits'],
    ('top', 'Register', 'FF'): ['body_P', 'body_P_fast', 'top_cores', 'top_wide_bits_fast', 'top_c_word'],
    ('top', 'Register', 'LUT'): [],
}


def collect(rows):
    data = collections.defaultdict(list)   # key -> list of (x dict, y, weight, sample, group)
    for r in rows:
        s = sanitize.sanitize(r['input_hs'])
        tgt = r['targets']
        for mm in s['module_hierarchy']:
            m = mm['module']
            cls = features.module_class(m)
            f = features.module_features(s, m)
            cat = tgt['per_module'][m]['by_category']
            for (c, cat_name, res), basis in BASIS.items():
                if c != cls:
                    continue
                y = cat[cat_name][res]
                if cat_name == 'Expression':
                    # pipelined shl expressions are costed explicitly (resources.core_cost, same
                    # library cost as the lshr core): remove them from the fitted remainder
                    n_shl = sum(a['count_in_module'] for a in s['aux_operators']
                                if a['owner'] == m and a['params'].get('op') == 'shl')
                    y -= n_shl * resources.LSHR_COST[res]
                # relative error of the sample total: residual / T  -> weight 1/T^2 in least squares
                w = (mm['instantiations'] / max(1, tgt[res])) ** 2
                data[(c, cat_name, res)].append((f, y, w, r['sample'], r['suite']))
    return data


def fit(data, holdout=None):
    consts = {}
    for key, basis in BASIS.items():
        if not basis:
            consts['|'.join(key)] = dict(FIXED.get(key, {}))
            continue
        pts = [p for p in data[key] if p[4] != holdout]
        X = np.array([[p[0].get(b, 0.0) for b in basis] for p in pts], dtype=float)
        fx = FIXED.get(key, {})
        y = np.array([p[1] - sum(c * p[0].get(b, 0.0) for b, c in fx.items()) for p in pts], dtype=float)
        w = np.sqrt(np.array([p[2] for p in pts]))
        coef, _ = nnls(X * w[:, None], y * w)
        consts['|'.join(key)] = {**{b: float(c) for b, c in zip(basis, coef)}, **fx}
    return consts


if __name__ == '__main__':
    rows = evaluate.load()
    data = collect(rows)
    consts = fit(data)
    here = os.path.dirname(os.path.abspath(__file__))
    json.dump(consts, open(os.path.join(here, 'constants.json'), 'w'), indent=1)
    # human-readable copy (authoritative values; STAGE2_MODEL.md explains each quantity)
    L = ['# Stage 2 per-unit constants (generated by fit.py from constants.json)', '',
         'Fixed-by-physics terms are marked (fixed). Meaning of each quantity: STAGE2_MODEL.md section 2.', '',
         '| class / category / resource | quantity | value |', '|---|---|---|']
    for k, v in consts.items():
        fx = FIXED.get(tuple(k.split('|')), {})
        for b, c in v.items():
            L.append(f"| {k.replace('|', ' / ')} | {b} | {c:.4g}{' (fixed)' if b in fx else ''} |")
    open(os.path.join(here, 'reports', 'CONSTANTS.md'), 'w').write('\n'.join(L) + '\n')
    # support of each fitted term: number of designs (of 510) in which its quantity is non-zero;
    # predict.py flags a design whose prediction uses a term supported by fewer than 10 designs
    sup = {}
    for key, pts in data.items():
        for b in BASIS.get(key, []):
            sup['|'.join(key) + '|' + b] = len({p[3] for p in pts if p[0].get(b, 0.0)})
    json.dump(sup, open(os.path.join(here, 'term_support.json'), 'w'), indent=1)
    for k, v in consts.items():
        print(k, {b: round(c, 3) for b, c in v.items()})
